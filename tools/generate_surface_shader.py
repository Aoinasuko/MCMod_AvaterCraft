"""Synchronize the shared property schema and generate repetitive atlas sampler functions."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'unity/Packages/dev.avatarcraft.exporter/Editor/Resources/AvatarCraft/surface.json'
TARGET = ROOT / 'src/main/resources/assets/avatarcraft'

def generate():
    schema = json.loads(SOURCE.read_text(encoding='utf-8'))
    (TARGET / 'surface.json').write_bytes(SOURCE.read_bytes())
    lines = ['// Generated by tools/generate_surface_shader.py; wrap before atlas lookup.',
             'vec2 surfaceWrap(vec2 p, vec2 mode) {',
             '  vec2 repeatUv=fract(p), mirrorUv=1.0-abs(mod(p,2.0)-1.0);',
             '  return vec2(mode.x==1.0?clamp(p.x,0.0,1.0):mode.x==2.0?mirrorUv.x:mode.x==3.0?clamp(abs(p.x),0.0,1.0):repeatUv.x,',
             '              mode.y==1.0?clamp(p.y,0.0,1.0):mode.y==2.0?mirrorUv.y:mode.y==3.0?clamp(abs(p.y),0.0,1.0):repeatUv.y);', '}',
             'vec2 surfaceTransform(vec2 p, vec4 st) { return vec2(p.x*st.x+st.z,1.0-((1.0-p.y)*st.y+st.w)); }']
    for slot in schema['slots']:
        k='T'+slot.upper()
        default='vec4(0.5,0.5,1.0,1.0)' if 'Bump' in slot and 'Mask' not in slot else 'vec4(0.5)' if slot.endswith('NoiseMask') else 'vec4(1.0)'
        lines += [f'vec4 tex{slot}(vec2 p) {{', f'#if {k}_HAS > 0',
                  f'  p=surfaceTransform(p,vec4({k}_SX,{k}_SY,{k}_OX,{k}_OY));',
                  f'  p=surfaceWrap(p,vec2({k}_WU,{k}_WV));',
                  f'  return texture(Sampler1,vec2({k}_X,{k}_Y)+p*vec2({k}_W,{k}_H));',
                  '#else',f'  return {default};','#endif','}']
    # Vector convenience aliases have numeric values supplied by SurfaceMaterial.defines.
    for prop in schema['vectors']:
        k='S'+prop.upper()
        lines.append(f'#define {k} vec4({k}_X,{k}_Y,{k}_Z,{k}_W)')
    (TARGET / 'shaders/include/surface_textures.glsl').parent.mkdir(parents=True, exist_ok=True)
    (TARGET / 'shaders/include/surface_textures.glsl').write_text('\n'.join(lines)+'\n',encoding='utf-8')

    effects = []
    for ordinal in ['2nd','3rd']:
        p='_Main'+ordinal
        k='S'+p.upper()
        color='S_COLOR'+ordinal.upper()
        effects += [f'vec4 layer{ordinal}(vec2 base,vec3 n,vec3 v,vec3 position,out vec3 edgeColor) {{',
                    '  edgeColor=vec3(0.0);',f'  if(S_USEMAIN{ordinal.upper()}TEX<=0.0) return vec4(0.0);',
                    f'  vec2 p=animatedUv(layerUv(base,{k}TEX_UVMODE,n,v),{k}TEX_SCROLLROTATE,{k}TEXANGLE);',
                    f'  vec4 c=tex{p}Tex(p)*{color};',f'  c.a*=tex{p}BlendMask(primaryUv(base)).r;']
        # Transform values are only emitted for present textures; a missing texture is constant white.
        effects += [f'#if T{p.upper()}TEX_HAS > 0',
                    f'  vec2 decal=surfaceTransform(p,vec4(T{p.upper()}TEX_SX,T{p.upper()}TEX_SY,T{p.upper()}TEX_OX,T{p.upper()}TEX_OY));',
                    f'  if({k}TEXISDECAL>0.0 && (any(lessThan(decal,vec2(0))) || any(greaterThan(decal,vec2(1))))) c.a=0.0;',
                    '#endif',
                    f'  if(({k}TEX_CULL==1.0 && gl_FrontFacing)||({k}TEX_CULL==2.0 && !gl_FrontFacing)) c.a=0.0;',
                    f'  if(({k}TEXISLEFTONLY>0.0 && base.x>=0.5)||({k}TEXISRIGHTONLY>0.0 && base.x<0.5)) c.a=0.0;',
                    '  float edge;',
                    f'  c.a*=dissolveValue(tex{p}DissolveMask(base).r,(tex{p}DissolveNoiseMask(base).r-0.5)*{k}DISSOLVENOISESTRENGTH,{k}DISSOLVEPARAMS,{k}DISSOLVEPOS,base,position,edge);',
                    f'  edgeColor={k}DISSOLVECOLOR.rgb*edge*c.a;', '  return c;', '}']
    for ordinal in ['', '2nd']:
        p='_MatCap'+ordinal; k='S'+p.upper()
        effects += [f'vec3 matcap{ordinal}(vec3 color,vec3 n,vec3 original,mat3 frame,vec3 v,vec2 p,vec3 lighting,float shade,float alpha) {{',
                    f'  if(S_USEMATCAP{ordinal.upper()}<=0.0) return color;',
                    f'  vec3 capNormal=safeNormal(mix(original,n,{k}NORMALSTRENGTH));',
                    f'  if({k}CUSTOMNORMAL>0.0) capNormal=safeNormal(frame*unpackSurfaceNormal(tex{p}BumpMap(primaryUv(p)),{k}BUMPSCALE));',
                    f'  vec4 cap=tex{p}Tex(matcapUv(capNormal,v,{k}PERSPECTIVE))*{k}COLOR;',
                    f'  cap.rgb*=mix(vec3(1),color,{k}MAINSTRENGTH);',
                    f'  cap.rgb*=mix(vec3(1),lighting,{k}ENABLELIGHTING);',
                    f'  vec3 amount=tex{p}BlendMask(primaryUv(p)).rgb*cap.a*{k}BLEND;',
                    f'  amount*=mix(1.0,shade,{k}SHADOWMASK)*mix(1.0,alpha,{k}APPLYTRANSPARENCY);',
                    f'  if({k}BACKFACEMASK>0.0 && !gl_FrontFacing) amount=vec3(0);',
                    f'  return surfaceBlend(color,cap.rgb,amount,{k}BLENDMODE);', '}']
    for ordinal in ['', '2nd']:
        p='_Emission'+ordinal; k='S'+p.upper()
        effects += [f'vec3 emission{ordinal}(vec3 color,vec3 base,vec2 p,vec3 n,vec3 v,float alpha) {{',
                    f'  if(S_USEEMISSION{ordinal.upper()}<=0.0) return color;',
                    f'  vec2 u=animatedUv(layerUv(p,{k}MAP_UVMODE,n,v),{k}MAP_SCROLLROTATE,0.0);',
                    f'  vec4 e=tex{p}Map(u)*{k}COLOR;',
                    f'  e.rgb*=mix(vec3(1),base,{k}MAINSTRENGTH);',
                    f'  vec3 amount=tex{p}BlendMask(primaryUv(p)).rgb*e.a*{k}BLEND;',
                    f'  return surfaceBlend(color,e.rgb,amount,{k}BLENDMODE);', '}']
    (TARGET / 'shaders/include/surface_effects.glsl').write_text('\n'.join(effects)+'\n',encoding='utf-8')

if __name__ == '__main__': generate()
